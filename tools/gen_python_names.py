#!/usr/bin/env python3
"""Write lib/check/python_names.mbt: the Python names the reference classifies by.

The reference checker (isabelle-purepy's `messages.excluded_feature`) asks
the Python it runs on whether a refused name is a built-in (`dir(builtins)`),
a standard-library module (`sys.stdlib_module_names`), a member of one of
the predefined modules (`hasattr(sys, x)`, ...) or an attribute of a built-in
type (`hasattr(list, x)`, ...). If it is, the refusal is of an excluded
Python feature and carries a classification; otherwise it is an ordinary
ill-formed program. This port has no Python at run time, so the answers are
tables, generated by the Python the goldens are generated with.

Usage: python3 tools/gen_python_names.py
"""

import builtins
import dataclasses
import pathlib
import sys
import typing

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "check" / "python_names.mbt"

TYPES = {"list": list, "dict": dict, "tuple": tuple, "bool": bool, "int": int,
         "float": float, "str": str}
MODULES = {"sys": sys, "typing": typing, "dataclasses": dataclasses}


def array(name: str, doc: str, names: list[str]) -> str:
    body = "".join(f"  {n!r},\n".replace("'", '"') for n in sorted(set(names)))
    return f"///|\n/// {doc}\nlet {name} : Array[String] = [\n{body}]\n"


def main() -> None:
    v = sys.version_info
    parts = [
        f"// Generated by tools/gen_python_names.py from Python "
        f"{v.major}.{v.minor}.{v.micro}; do not edit.\n",
        array("python_builtins", "`dir(builtins)`.", dir(builtins)),
        array("python_builtin_classes", "The built-ins that are classes.",
              [x for x in dir(builtins) if isinstance(getattr(builtins, x), type)]),
        array("python_stdlib_modules", "`sys.stdlib_module_names`.",
              list(sys.stdlib_module_names)),
    ]
    for m, mod in MODULES.items():
        parts.append(array(f"python_members_{m}", f"`dir({m})`.", dir(mod)))
    for t, ty in TYPES.items():
        parts.append(array(f"python_attrs_{t}", f"`dir({t})`.", dir(ty)))
    parts.append("""///|
/// The members of a predefined module, by its name, as `hasattr` sees them.
fn python_module_members(m : String) -> Array[String]? {
  match m {
""" + "".join(f'    "{m}" => Some(python_members_{m})\n' for m in MODULES) + """    _ => None
  }
}

///|
/// The attributes of a built-in type, by its Python class name.
fn python_type_attrs(t : String) -> Array[String]? {
  match t {
""" + "".join(f'    "{t}" => Some(python_attrs_{t})\n' for t in TYPES) + """    _ => None
  }
}
""")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
